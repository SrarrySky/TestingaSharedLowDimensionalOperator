def load_geometry() -> dict:
    """
    Load geometry diagnostics generated by the experiment runner.
    :return: geometry, dict: Deserialized geometry result payload.
    """
    with np.load(GEOM / "geometry_paths.npz", allow_pickle=False) as z:
        return {k: z[k] for k in z.files}


def panel_label(ax, text: str, x: float = -0.30, y: float = 1.02) -> None:
    """
    Add a consistent panel label to a matplotlib axis.
    :param ax, matplotlib.axes.Axes: Axis receiving the label.
    :param text, str: Label text, typically a letter.
    :param x, float: Relative horizontal placement.
    :param y, float: Relative vertical placement.
    :return: None.
    """
    ax.text(x, y, text, transform=ax.transAxes, fontsize=8.5, fontweight="bold", va="bottom")


