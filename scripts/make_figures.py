def save(fig: plt.Figure, name: str) -> None:
    """
    Save a publication figure in the configured output formats.
    :param fig, matplotlib.figure.Figure: Figure object to serialize.
    :param name, str: Stable artifact name without extension.
    :return: None.
    """
    fig.savefig(FIG / f"{name}.pdf", format="pdf", bbox_inches="tight", pad_inches=0.05)
    plt.close(fig)
    print("wrote", FIG / f"{name}.pdf")


