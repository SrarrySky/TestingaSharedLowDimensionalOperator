# fig02 — coefficient-path increment spectrum (model-internal diagnostic)
# --------------------------------------------------------------------------- #
def fig02_lowrank() -> None:
    g = load_geometry()
    cp = g["coefficient_path"]  # (T, p) already restricted to a0 + B z
    inc = np.diff(cp, axis=0)
    _, s, _ = np.linalg.svd(inc, full_matrices=False)
    with open(GEOM / "geometry.json", encoding="utf-8") as fh:
        eff = json.load(fh)["low_rank"]["diagnostics"]["effective_rank"]

    fig, ax = plt.subplots(figsize=(FW, 2.3))
    k = np.arange(1, 16)
    ax.plot(k, s[:15], "o-", ms=3.0, lw=0.9, color="#0072B2", mfc="#0072B2")
    ax.axvline(2, color=NULL, lw=0.8, ls=":")
    ax.text(
        2.05, 0.92 * s[0], f"effective rank = {eff:.2f}", fontsize=6.8, color="#0072B2", ha="left"
    )
    ax.set_yscale("log")
    ax.set_xlabel("Singular-value index of centred coefficient increments")
    ax.set_ylabel("Singular value (log)")
    ax.set_xticks(k)
    ax.set_xlim(0.5, 15.5)
    fig.text(
        0.01,
        -0.06,
        "Model-internal diagnostic (DLC-restricted path $a_0+\\mathbf{B}z_t$); "
        "not independent low-rank evidence.",
        fontsize=5.8,
        color="#666666",
    )
    fig.tight_layout()
    save(fig, "fig02-lowrank")


