def _split_background(ax, dates, split) -> None:
    t0 = dates[0]
    tv = dates[np.asarray(split) == "train"].max()
    tt = dates[np.asarray(split) == "validation"].max()
    end = dates[-1]
    ax.axvspan(t0, tv, color="#f2f7fb", zorder=0)
    ax.axvspan(tv, tt, color="#fff8ee", zorder=0)
    ax.axvspan(tt, end, color="#fbf3f3", zorder=0)
    ax.set_xlim(t0, end)


def fig03_state() -> None:
    d = load_dataset()
    dates, split = d["dates"], d["split"]
    g = load_geometry()
    st = g["states"]
    sr = g["spectral_radii"]
    pg = g["peak_gains"]
    sba = g["stable_but_amplifying"]
    t = dates[1:]
    sp = split[1:]
    # Independent vector assets; panel arrangement belongs to LaTeX.
    fig, ax = plt.subplots(figsize=(2.35, 1.9))
    for part in ("train", "validation", "test"):
        m = sp == part
        ax.scatter(st[m, 0], st[m, 1], s=2.5, alpha=0.35, color=SPLIT_COLOR[part], label=part, lw=0)
    ax.set_xlabel("$z_1$")
    ax.set_ylabel("$z_2$")
    ax.legend(loc="upper right", fontsize=6, markerscale=1.5, handletextpad=0.1, borderpad=0.2)
    fig.tight_layout(pad=0.5)
    save(fig, "fig03-state-sign")

    for values, ylabel, name, color in (
        (sr, "Spectral radius", "fig03-spectral-radius", "#0072B2"),
        (pg, "Frozen peak gain", "fig03-peak-gain", "#D55E00"),
    ):
        fig, ax = plt.subplots(figsize=(2.35, 1.9))
        ax.plot(t, values, lw=0.35, color=color)
        ax.set_ylabel(ylabel)
        if name == "fig03-peak-gain":
            ax.axhline(1.0, color=NULL, lw=0.7, ls="--")
            ax.plot(t[sba], pg[sba], "o", ms=2, color="#8a0000", mec="none", zorder=4)
        _split_background(ax, dates, split)
        ax.xaxis.set_major_locator(matplotlib.dates.YearLocator(4))
        ax.xaxis.set_major_formatter(matplotlib.dates.DateFormatter("%Y"))
        ax.set_xlabel("Year")
        fig.tight_layout(pad=0.5)
        save(fig, name)


def fig04_migration() -> None:
    with np.load(OOS / "design" / "features.npz", allow_pickle=False) as z:
        names = [str(n) for n in z["feature_names"]]
        X = z["X"]
        split = np.asarray(z["split"])
        fg = X[:, names.index("geom__frozen_gain_h5")]
        mg = X[:, names.index("geom__state_migration_gap_h5")]
    fig, ax = plt.subplots(figsize=(2.35, 2.35))
    for part in ("train", "validation", "test"):
        m = split == part
        ax.scatter(fg[m], mg[m], s=2.5, alpha=0.4, color=SPLIT_COLOR[part], label=part, lw=0)
    lim = (min(fg.min(), mg.min()), max(fg.max(), mg.max()))
    ax.plot(lim, lim, ls="--", lw=0.7, color=NULL)
    ax.set_xlabel("Frozen gain")
    ax.set_ylabel("Migration gap")
    ax.legend(fontsize=8.5, markerscale=1.5)
    fig.tight_layout(pad=0.5)
    save(fig, "fig04-migration")


def fig05_response() -> None:
    d = load_dataset()
    g = load_geometry()
    lag_path = g["lag_path"]  # (T, 1, n, n) with [ell, target, source]
    sp = d["split"][1:]
    idx = int(np.flatnonzero(sp == "train")[-1])
    A = lag_path[idx, 0]  # (n_target, n_source)
    vmax = float(np.max(np.abs(A))) or 1.0

    fig = plt.figure(figsize=(2.35, 2.7))
    # Give the square matrix most of the panel area.  The previous tight-layout
    # box was very wide relative to its height, so LaTeX's square image slot
    # shrank the heatmap vertically when keeping the PDF aspect ratio.
    ax = fig.add_axes([0.22, 0.18, 0.70, 0.70])
    im = ax.imshow(A, cmap="coolwarm", vmin=-vmax, vmax=vmax, aspect="equal")
    ticks = np.array([0, 4, 9, 14, 19, 24, 30])
    ax.set_xticks(ticks, labels=[str(i + 1) for i in ticks])
    ax.set_yticks(ticks, labels=[str(i + 1) for i in ticks])
    ax.tick_params(length=0)
    ax.set_xlabel("Source sector (1–31)")
    ax.set_ylabel("Target sector (1–31)")
    cb = fig.colorbar(im, cax=fig.add_axes([0.94, 0.18, 0.035, 0.70]))
    cb.ax.tick_params(labelsize=6)
    cb.set_label("$A_{\\ell=1,ji}$", fontsize=7)
    ax.set_title(f"Last Train: {d['dates'][idx + 1]:%Y-%m-%d}", fontsize=7)
    save(fig, "fig05-response")


