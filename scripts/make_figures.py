def fig01_framework() -> None:
    fig, ax = plt.subplots(figsize=(FW, 2.6))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 10)
    ax.axis("off")

    def box(cx, cy, w, h, text, fc="#eef3f8", ec="#33475b", fs=7.2, bold=False):
        ax.add_patch(
            FancyBboxPatch(
                (cx - w / 2, cy - h / 2),
                w,
                h,
                boxstyle="round,pad=0.06,rounding_size=0.10",
                fc=fc,
                ec=ec,
                lw=0.8,
            )
        )
        ax.text(
            cx,
            cy,
            text,
            ha="center",
            va="center",
            fontsize=fs,
            fontweight="bold" if bold else "normal",
            linespacing=1.35,
        )

    def arrow(x1, y1, x2, y2, text=""):
        ax.add_patch(
            FancyArrowPatch(
                (x1, y1), (x2, y2), arrowstyle="-|>", mutation_scale=9, lw=0.8, color="#33475b"
            )
        )
        if text:
            mx, my = (x1 + x2) / 2, (y1 + y2) / 2
            ax.text(mx + 0.16, my + 0.08, text, fontsize=6.4, color="#33475b", ha="left")

    # row positions
    y1, y2, y3 = 8.4, 5.3, 2.2
    box(2.4, y1, 3.6, 1.15, "Observed sector returns $x_t$\n+ market covariates $u_t$")
    box(7.7, y1, 3.6, 1.15, "Train-only causal screen\n(LPCMCI) $\\to$ directed support")
    box(
        5.1,
        y2,
        4.6,
        1.25,
        "Shared latent operator\n$z_t=Fz_{t-1}+Gu_t+\\eta_t$,\n$a_t=a_0+\\mathbf{B}z_t$",
    )
    box(
        2.2,
        y3,
        3.3,
        1.35,
        "State-conditioned companion\n$C(z_t)$, spectral radius,\nnon-normality, finite gain",
    )
    box(
        7.7,
        y3,
        3.6,
        1.35,
        "Frozen vs. time-ordered\npropagation, migration gap,\nstate sensitivity",
    )
    box(5.1, 0.4, 4.6, 0.95, "Nested downside prediction $M_0$--$M_5$ (held-out)", fc="#f3eef5")
    arrow(4.3, y1, 5.8, y1)
    arrow(2.4, y1 - 0.62, 4.6, y2 + 0.68)
    arrow(7.7, y1 - 0.62, 5.6, y2 + 0.68)
    arrow(4.4, y2 - 0.70, 2.6, y3 + 0.75)
    arrow(5.9, y2 - 0.70, 7.4, y3 + 0.75)
    arrow(2.2, y3 - 0.72, 4.4, 0.9)
    arrow(7.7, y3 - 0.72, 5.8, 0.9)
    # empty-support branch annotation
    ax.annotate(
        r"empty support $\Rightarrow$ common-factor fit",
        xy=(5.1, y2 - 0.72),
        xytext=(0.9, 0.05),
        textcoords="offset points",
        fontsize=6.2,
        color="#8a5a00",
        ha="center",
        arrowprops=dict(arrowstyle="-", lw=0.5, color="#8a5a00"),
    )
    save(fig, "fig01-framework")


