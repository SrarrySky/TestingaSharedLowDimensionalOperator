# fig06 — nested downside prediction (core result)
# --------------------------------------------------------------------------- #
def fig06_oos() -> None:
    m = pd.read_csv(OOS / "metrics.csv").query("split == 'test'")
    cmp = pd.read_csv(OOS / "comparisons.csv")
    order = ["M0", "M1", "M2", "M3", "M4", "M5"]
    mse = m.set_index("model").reindex(order)["mse"].to_numpy() * 1e8
    # nested adjacent comparisons only
    adj = cmp[
        cmp.apply(
            lambda r: (
                f"{r.reference}->{r.candidate}"
                in {"M0->M1", "M1->M2", "M2->M3", "M3->M4", "M4->M5"}
            ),
            axis=1,
        )
    ]
    rel = (
        adj.set_index("candidate")
        .reindex(order[1:])[["relative_mse_improvement", "relative_ci_low", "relative_ci_high"]]
        .to_numpy()
    ) * 100

    fig, ax = plt.subplots(figsize=(2.35, 2.0))
    # (a) nested Test MSE
    x = np.arange(6)
    ax.bar(x, mse, 0.55, color=["#c9c9c9"] + ["#6fa8dc"] * 5, edgecolor="#33475b", lw=0.5)
    ax.axhline(1.9306, color=NEG, lw=0.9, ls="--")
    ax.text(0.1, 1.87, "Train-mean benchmark", color=NEG, fontsize=9.5, va="top")
    for xi, v in zip(x, mse, strict=False):
        ax.text(xi, v + 0.03, f"{v:.2f}", ha="center", fontsize=8.5)
    ax.set_xticks(x)
    ax.set_xticklabels(order)
    ax.set_ylabel("Test MSE  ($\\times 10^{-8}$)")
    ax.set_ylim(0, 2.75)
    ax.set_xlim(-0.5, 5.9)
    fig.tight_layout(pad=0.5)
    save(fig, "fig06-oos")

    # (b) nested incremental relative improvement (positive = lower MSE)
    fig, ax = plt.subplots(figsize=(2.35, 2.0))
    ypos = np.arange(len(rel))[::-1]
    ax.errorbar(
        rel[:, 0],
        ypos,
        xerr=[rel[:, 0] - rel[:, 1], rel[:, 2] - rel[:, 0]],
        fmt="o",
        ms=3.2,
        color=REF,
        ecolor=REF,
        elinewidth=0.9,
        capsize=2.5,
        capthick=0.7,
        zorder=3,
    )
    ax.axvline(0, color=NULL, lw=0.9, ls="--", zorder=1)
    for y, r in zip(ypos, rel, strict=False):
        ax.plot(r[0], y, "o", ms=4.0, color=NEG if r[0] < 0 else POS, zorder=4)
    ax.set_yticks(ypos)
    ax.set_yticklabels(["$M_1-M_0$", "$M_2-M_1$", "$M_3-M_2$", "$M_4-M_3$", "$M_5-M_4$"])
    ax.set_xlabel("Relative MSE improvement (%)")
    ax.set_xlim(-16, 3)
    ax.axhline(-0.5, color="#dddddd", lw=0.5)
    fig.tight_layout(pad=0.5)
    save(fig, "fig06-oos-increments")


